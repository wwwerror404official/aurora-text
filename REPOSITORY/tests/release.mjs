import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import vm from "node:vm";
const root = fileURLToPath(new URL("../", import.meta.url));
const read = (name) => readFile(resolve(root, name), "utf8");
const manifest = JSON.parse(await read("manifest.json"));
const pkg = JSON.parse(await read("package.json"));
const versions = JSON.parse(await read("versions.json"));
assert.equal(manifest.version, pkg.version);
assert.equal(versions[manifest.version], manifest.minAppVersion);
assert.match(manifest.version, /^\d+\.\d+\.\d+$/);
assert(
  manifest.description.length <= 250 && manifest.description.endsWith("."),
);
const css = await read("styles.css"),
  js = await read("main.js");
assert.equal(css, await read("src/effects.css"));
const parts = ["i18n", "core", "letters", "ui", "compact", "plugin"];
const source = (await Promise.all(parts.map((n) => read(`src/${n}.js`)))).join(
  "\n",
);
assert.equal(
  js,
  `/* Aurora Text ${manifest.version} | MIT | Generated by npm run build. Edit src/. */\n` +
    source,
);
assert(
  !/@import\b|url\(\s*['"]?https?:/i.test(css),
  "CSS assets must stay local",
);
assert(
  !/\b(?:fetch|XMLHttpRequest|WebSocket|eval)\s*\(/.test(js),
  "No network or evaluated source",
);
const context = { navigator: { language: "en-US" } };
vm.createContext(context);
vm.runInContext(
  (await read("src/i18n.js")) +
    "\n" +
    (await read("src/core.js")) +
    "\nthis.i18n=AuroraI18n;this.core=AuroraTextCore;",
  context,
);
assert.equal(context.core.byId("whitegold").name, "White Gold");
assert.equal(context.core.byId("sick").name, "Sick?");
assert.throws(() => context.core.target("x", 0, 0), /Select some words/);
context.i18n.setLanguage("ru");
assert.equal(context.core.byId("whitegold").name, "Белое золото");
context.i18n.setLanguage("en");
for (const style of context.core.styles) {
  assert(
    !/[А-Яа-яЁё]/.test(style.name + " " + style.desc),
    `Missing translation: ${style.id}`,
  );
}
// Each generated wrapper round-trips exactly, in either language.
for (const lang of ["en", "ru"]) {
  context.i18n.setLanguage(lang);
  for (const style of context.core.styles) {
    const text = "A & B < C 👩‍🚀";
    const target = context.core.target(text, 0, text.length);
    const value = context.core.build(target, style, {
      seed: 17,
      color: "#ffaa00",
    });
    assert.equal(context.core.target(value, 0, value.length).plain, text);
  }
}
for (const file of [
  "LICENSE",
  "README.md",
  "docs/QA.md",
  "docs/PRIVACY.md",
  "docs/demo.html",
])
  assert((await read(file)).length > 100, file);
console.log(
  "Release checks passed: build parity, metadata, offline assets, EN/RU, all 42 wrapper round-trips.",
);
