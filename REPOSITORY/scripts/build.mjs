import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { execFileSync } from "node:child_process";
const root = fileURLToPath(new URL("../", import.meta.url));
const read = (name) => readFile(resolve(root, name), "utf8");
const manifest = JSON.parse(await read("manifest.json"));
const parts = ["i18n", "core", "letters", "ui", "compact", "plugin"];
const sources = await Promise.all(parts.map((name) => read(`src/${name}.js`)));
const banner = `/* Aurora Text ${manifest.version} | MIT | Generated by npm run build. Edit src/. */\n`;
await writeFile(resolve(root, "main.js"), banner + sources.join("\n"));
await writeFile(resolve(root, "styles.css"), await read("src/effects.css"));
execFileSync(process.execPath, ["--check", resolve(root, "main.js")], {
  stdio: "inherit",
});
await mkdir(resolve(root, "docs"), { recursive: true });
const template = await read("src/demo.html");
const demo = template
  .replace("/* AURORA_CSS */", await read("styles.css"))
  .replace("/* AURORA_JS */", sources.slice(0, -1).join("\n"));
await writeFile(resolve(root, "docs/demo.html"), demo);
console.log(
  `Built Aurora Text ${manifest.version}: main.js, styles.css, docs/demo.html`,
);
